export function knowledgeCheckFor(courseKey: string, lessonId: string): KnowledgeCheck | null {
  return checks[courseKey]?.find(item => item.unitId === lessonId) ?? null;
}
export function allKnowledgeChecks(): ReadonlyArray<{ courseKey: string; check: KnowledgeCheck }> {
  return Object.entries(checks).flatMap(([courseKey, items]) => items.map(check => ({ courseKey, check })));
}
