"""Policy-bound career-grade readiness projection.

A career grade is NOT competency level, XP, course progress or A/B/C review.
There is intentionally no built-in catalog: policy approval/publication must
precede computation and any automatic transition. This module makes server
calculation deterministic and safe without granting grades by itself.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from hashlib import sha256
from json import dumps
from uuid import UUID


class EvidenceState(StrEnum):
    VERIFIED = "verified"
    REPORTED = "reported"
    REJECTED = "rejected"
    REVOKED = "revoked"


@dataclass(frozen=True, slots=True)
class GradeRequirement:
    key: str
    title: str
    source_key: str
    source_version: str
    weight: int

    def __post_init__(self) -> None:
        if not all((self.key.strip(), self.title.strip(), self.source_key.strip())):
            raise ValueError("Requirement must have stable identity and source")
        if not self.source_version.strip() or self.weight <= 0:
            raise ValueError("Requirement must carry source version and positive weight")


@dataclass(frozen=True, slots=True)
class PublishedGradePolicy:
    """Externally reviewed and published catalog edge, never generated by UI."""

    track_key: str
    catalog_version: str
    calculation_version: str
    current_grade_key: str
    target_grade_key: str
    approval_ref: str
    effective_from: datetime
    effective_until: datetime | None
    requirements: tuple[GradeRequirement, ...]

    def __post_init__(self) -> None:
        identity = (
            self.track_key,
            self.catalog_version,
            self.calculation_version,
            self.current_grade_key,
            self.target_grade_key,
            self.approval_ref,
        )
        if any(not field.strip() for field in identity):
            raise ValueError("Published grade policy must have approval and versioned identity")
        if self.current_grade_key == self.target_grade_key:
            raise ValueError("A grade transition needs distinct source and target grades")
        if self.effective_from.tzinfo is None or self.effective_from.utcoffset() is None:
            raise ValueError("Policy effective timestamp must be timezone aware")
        if self.effective_until is not None and (
            self.effective_until.tzinfo is None
            or self.effective_until.utcoffset() is None
            or self.effective_until <= self.effective_from
        ):
            raise ValueError("Invalid policy expiry")
        if not self.requirements:
            raise ValueError("A transition must have explicit published requirements")
        keys = [requirement.key for requirement in self.requirements]
        if len(keys) != len(set(keys)):
            raise ValueError("Published requirement keys must be unique")


@dataclass(frozen=True, slots=True)
class GradeEvidence:
    person_id: UUID
    track_key: str
    requirement_key: str
    source_key: str
    source_version: str
    source_ref: str
    state: EvidenceState
    trusted: bool
    observed_at: datetime
    revoked_at: datetime | None = None

    def __post_init__(self) -> None:
        fields = (
            self.track_key,
            self.requirement_key,
            self.source_key,
            self.source_version,
            self.source_ref,
        )
        if any(not field.strip() for field in fields):
            raise ValueError("Evidence needs an attributable source and requirement")
        if self.observed_at.tzinfo is None or self.observed_at.utcoffset() is None:
            raise ValueError("Evidence event timestamp must be timezone aware")
        if self.revoked_at is not None and (
            self.revoked_at.tzinfo is None or self.revoked_at.utcoffset() is None
        ):
            raise ValueError("Revocation timestamp must be timezone aware")


@dataclass(frozen=True, slots=True)
class RequirementPosition:
    key: str
    title: str
    weight: int
    state: str
    verified_sources: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class GradeReadiness:
    state: str
    reason: str | None
    track_key: str
    current_grade_key: str | None
    target_grade_key: str | None
    catalog_version: str | None
    calculation_version: str | None
    as_of: datetime
    completed_percent: Decimal | None
    remaining_percent: Decimal | None
    requirements: tuple[RequirementPosition, ...]
    ready_for_atomic_transition: bool
    calculation_fingerprint: str | None


def calculate_grade_readiness(
    person_id: UUID,
    track_key: str,
    policy: PublishedGradePolicy | None,
    evidence: tuple[GradeEvidence, ...] = (),
    *,
    as_of: datetime,
) -> GradeReadiness:
    """Calculate a *proposal*; issuing a grade requires a separate durable owner.

    The evidence read must be a trusted server-side feed. Source IDs, role,
    person, version, verified state and revocations are checked again here.
    Repeated evidence events cannot inflate the weighted score.
    """

    if as_of.tzinfo is None or as_of.utcoffset() is None:
        raise ValueError("Calculation time must be timezone aware")

    if policy is None:
        return GradeReadiness(
            state="not_evaluable",
            reason="grade_catalog_policy_not_published",
            track_key=track_key,
            current_grade_key=None,
            target_grade_key=None,
            catalog_version=None,
            calculation_version=None,
            as_of=as_of,
            completed_percent=None,
            remaining_percent=None,
            requirements=(),
            ready_for_atomic_transition=False,
            calculation_fingerprint=None,
        )
    if policy.track_key != track_key:
        raise ValueError("Published grade policy belongs to another trajectory")
    if as_of < policy.effective_from or (
        policy.effective_until is not None and as_of >= policy.effective_until
    ):
        return GradeReadiness(
            state="not_evaluable",
            reason="grade_catalog_policy_not_effective",
            track_key=track_key,
            current_grade_key=None,
            target_grade_key=None,
            catalog_version=policy.catalog_version,
            calculation_version=policy.calculation_version,
            as_of=as_of,
            completed_percent=None,
            remaining_percent=None,
            requirements=(),
            ready_for_atomic_transition=False,
            calculation_fingerprint=None,
        )

    qualified: dict[str, tuple[str, ...]] = {}
    for requirement in policy.requirements:
        matching = tuple(
            item
            for item in evidence
            if item.person_id == person_id
            and item.track_key == track_key
            and item.requirement_key == requirement.key
            and item.source_key == requirement.source_key
            and item.source_version == requirement.source_version
            and item.trusted
            and item.observed_at <= as_of
        )
        revocations = frozenset(
            item.source_ref
            for item in matching
            if item.state is EvidenceState.REVOKED
            or (item.revoked_at is not None and item.revoked_at <= as_of)
        )
        good = sorted(
            {
                item.source_ref
                for item in matching
                if item.state is EvidenceState.VERIFIED
                and item.revoked_at is None
                and item.source_ref not in revocations
            }
        )
        qualified[requirement.key] = tuple(good)

    positions = tuple(
        RequirementPosition(
            key=requirement.key,
            title=requirement.title,
            weight=requirement.weight,
            state="verified" if qualified[requirement.key] else "not_verified",
            verified_sources=qualified[requirement.key],
        )
        for requirement in policy.requirements
    )
    total_weight = sum(item.weight for item in positions)
    verified_weight = sum(item.weight for item in positions if item.state == "verified")
    completed = Decimal(verified_weight) * Decimal(100) / Decimal(total_weight)
    remaining = Decimal(100) - completed
    ready = verified_weight == total_weight
    fingerprint = sha256(
        dumps(
            {
                "person_id": str(person_id),
                "track": track_key,
                "catalog": policy.catalog_version,
                "calculation": policy.calculation_version,
                "approval_ref": policy.approval_ref,
                "from_grade": policy.current_grade_key,
                "to_grade": policy.target_grade_key,
                "evidence": [(item.key, item.verified_sources) for item in positions],
            },
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()
    return GradeReadiness(
        state="known",
        reason=None,
        track_key=track_key,
        current_grade_key=policy.current_grade_key,
        target_grade_key=policy.target_grade_key,
        catalog_version=policy.catalog_version,
        calculation_version=policy.calculation_version,
        as_of=as_of,
        completed_percent=completed,
        remaining_percent=remaining,
        requirements=positions,
        ready_for_atomic_transition=ready,
        calculation_fingerprint=fingerprint,
    )
